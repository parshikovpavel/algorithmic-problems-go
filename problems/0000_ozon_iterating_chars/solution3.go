// функция получения следующей лексикографической строки
func incrIndex(lengthAlpha int, indices []int) bool {
	// инкрементируем индексы, начиная с последних
	for i := len(indices) - 1; i >= 0; i-- {
		// пытаемся инкрементировать последний индекс
		indices[i]++
		// если он еще не вышел за количество символов (не превысил число в системе счисления = количеству символов)
		if indices[i] < lengthAlpha {
			// инкрементирование удалось, возвращаем true
			return true
		}
		// если вышли за количество символов, обнуляем соответствующий разряд
		indices[i] = 0
		// на следующей итерации попытаем инкрементировать старший разряд
	}
	// если прошлись по всем индексам и дошли до инкрементации разряда, которого уже нет -
	// уперлись в максимальную лексикографическую строку
	return false
}
